"""Local stand-in for the backend: serves a built frontend and answers /api/* from
fixtures/responses.json (generated by gen_fixtures.py). No live service is contacted.
Started by drive.py: stub_server.py BUILD_DIR PORT RESPONSES_JSON LOG_FILE
Any login token is accepted; /api/auth/me/ answers a "tourism" user."""
import json, os, sys, threading, time
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import urlparse, parse_qs

BUILD, PORT, RESP, LOG = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
data = json.load(open(RESP))
log_lock = threading.Lock()

def log(line):
    with log_lock:
        open(LOG, "a").write(f"{time.time():.3f} {line}\n")

class Handler(SimpleHTTPRequestHandler):
    def __init__(self, *a, **k):
        super().__init__(*a, directory=BUILD, **k)

    def log_message(self, *args):
        pass

    def _json(self, code, body):
        raw = json.dumps(body).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(raw)))
        self.end_headers()
        self.wfile.write(raw)

    def do_GET(self):
        u = urlparse(self.path)
        if u.path.startswith("/api/"):
            q = {k: v[0] for k, v in parse_qs(u.query).items()}
            log(f"GET {u.path} {json.dumps(q, sort_keys=True)}")
            if u.path == "/api/auth/me/":
                return self._json(200, {"user": {"id": 1, "username": "print-proof", "first_name": "Print", "last_name": "Proof",
                                                  "email": "", "profile": {"role": "tourism"}}})
            if u.path == "/api/bootstrap/":
                return self._json(200, data["bootstrap"])
            if u.path == "/api/reports/":
                year = q.get("year", "all"); typ = q.get("type", "resort")
                payload = dict(data["reports"][f"{typ}|{year}"])
                if str(q.get("include_questions", "true")).lower() not in ("false", "0", "no"):
                    payload["questionAnswers"] = data["reports"][f"questions|{year}"]
                # the real backend takes ~0.3 s a report from here; keep the app's timing realistic
                time.sleep(0.3)
                return self._json(200, payload)
            return self._json(200, {})
        # the single-page app: any other path that is not a file serves index.html
        if not os.path.exists(os.path.join(BUILD, u.path.lstrip("/"))) or u.path == "/":
            self.path = "/index.html"
        return super().do_GET()

    def do_POST(self):
        log(f"POST {self.path}")
        return self._json(200, {})

ThreadingHTTPServer(("127.0.0.1", PORT), Handler).serve_forever()
